#!/usr/bin/env bash
# United MFL — put the stack behind real domains with HTTPS (host nginx + Let's Encrypt).
#
#   sudo ./deploy/domains.sh unitedmfl.uz unitedmfl.com
#
# Main domain (1st argument):
#   https://unitedmfl.uz          — site            (www. → 301 to the apex)
#   https://admin.unitedmfl.uz    — admin panel
#   https://ariza.unitedmfl.uz    — team registration
# Extra domains (any further arguments, e.g. unitedmfl.com):
#   their apex, www., admin. and ariza. answer with a 301 to the same place on the main domain.
#
# DNS first: every host above needs an A record pointing at this server.
# Re-running is safe: the nginx file is rewritten, certbot only renews/extends.
# Env: LE_EMAIL=you@example.com for Let's Encrypt expiry mail (optional).
set -euo pipefail

[ "$(id -u)" = 0 ] || { echo "run with sudo" >&2; exit 1; }
[ $# -ge 1 ] || { sed -n '2,15p' "$0"; exit 1; }

MAIN="$1"; shift
EXTRA=("$@")
DIR="$(cd "$(dirname "$0")/.." && pwd)"
CONF=/etc/nginx/sites-available/unitedmfl

log()  { printf '\033[1;32m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m!!\033[0m %s\n' "$*"; }

# ---- 1. hostnames and a DNS check ----
names=("$MAIN" "www.$MAIN" "admin.$MAIN" "ariza.$MAIN")
for d in "${EXTRA[@]}"; do names+=("$d" "www.$d" "admin.$d" "ariza.$d"); done

my_ip="$(curl -fsS4 --max-time 5 https://api.ipify.org 2>/dev/null || hostname -I | awk '{print $1}')"
ready=()
for n in "${names[@]}"; do
  ip="$(getent ahostsv4 "$n" 2>/dev/null | awk 'NR==1{print $1}')"
  if [ "$ip" = "$my_ip" ]; then
    ready+=("$n")
  else
    warn "$n → ${ip:-no A record} (this server is $my_ip) — skipped for HTTPS until DNS points here"
  fi
done
for must in "$MAIN" "admin.$MAIN" "ariza.$MAIN"; do
  printf '%s\n' "${ready[@]}" | grep -qx "$must" || { echo "DNS for $must does not point to $my_ip yet — fix DNS and re-run" >&2; exit 1; }
done

# ---- 2. nginx + certbot ----
if ! command -v nginx >/dev/null || ! command -v certbot >/dev/null || ! dpkg -s python3-certbot-nginx >/dev/null 2>&1; then
  log "Installing nginx and certbot"
  apt-get update -qq
  apt-get install -y -qq nginx certbot python3-certbot-nginx
fi

# ---- 3. nginx config (HTTP; certbot adds the 443 parts) ----
proxy() { # $1 port, $2 extra lines
  cat <<EOF
    location / {
        proxy_pass http://127.0.0.1:$1;
        proxy_http_version 1.1;
        proxy_set_header Host \$host;
        proxy_set_header X-Forwarded-For \$remote_addr;
        proxy_set_header X-Forwarded-Proto \$scheme;
        proxy_set_header Upgrade \$http_upgrade;
        proxy_set_header Connection \$umfl_connection_upgrade;
        proxy_read_timeout 1h;
$2
    }
EOF
}
redirects=""
for d in "${EXTRA[@]}"; do
  redirects+="
server {
    listen 80;
    listen [::]:80;
    server_name $d www.$d;
    return 301 https://$MAIN\$request_uri;
}
server {
    listen 80;
    listen [::]:80;
    server_name admin.$d;
    return 301 https://admin.$MAIN\$request_uri;
}
server {
    listen 80;
    listen [::]:80;
    server_name ariza.$d;
    return 301 https://ariza.$MAIN\$request_uri;
}
"
done

log "Writing $CONF"
cat > "$CONF" <<EOF
# United MFL — generated by deploy/domains.sh, re-run the script instead of editing.
map \$http_upgrade \$umfl_connection_upgrade { default upgrade; '' close; }

server {
    listen 80;
    listen [::]:80;
    server_name www.$MAIN;
    return 301 https://$MAIN\$request_uri;
}

server {
    listen 80;
    listen [::]:80;
    server_name $MAIN;
    client_max_body_size 25m;
$(proxy 8120 "")
    # live match updates (Server-Sent Events): no buffering
    location /api/v1/live/ {
        proxy_pass http://127.0.0.1:8120;
        proxy_http_version 1.1;
        proxy_set_header Host \$host;
        proxy_set_header X-Forwarded-For \$remote_addr;
        proxy_set_header X-Forwarded-Proto \$scheme;
        proxy_set_header Connection "";
        proxy_buffering off;
        proxy_cache off;
        proxy_read_timeout 1h;
    }
}

server {
    listen 80;
    listen [::]:80;
    server_name admin.$MAIN;
    client_max_body_size 25m;
$(proxy 8121 "        proxy_buffering off;")
    # video files (Videolar → «Fayl yuklash»): a big body streamed straight to the API
    location /api/v1/admin/video-uploads {
        proxy_pass http://127.0.0.1:8121;
        proxy_http_version 1.1;
        proxy_set_header Host \$host;
        proxy_set_header X-Forwarded-For \$remote_addr;
        proxy_set_header X-Forwarded-Proto \$scheme;
        proxy_set_header Connection "";
        client_max_body_size 2100m;
        proxy_request_buffering off;
        proxy_read_timeout 3h;
        proxy_send_timeout 3h;
    }
}

server {
    listen 80;
    listen [::]:80;
    server_name ariza.$MAIN;
    client_max_body_size 25m;
$(proxy 8122 "")
}
$redirects
EOF
ln -sf "$CONF" /etc/nginx/sites-enabled/unitedmfl
nginx -t
systemctl enable --now nginx >/dev/null 2>&1 || true
systemctl reload nginx

# ---- 4. HTTPS ----
log "Requesting certificates for: ${ready[*]}"
args=(--nginx --non-interactive --agree-tos --redirect --expand --cert-name "$MAIN")
if [ -n "${LE_EMAIL:-}" ]; then args+=(-m "$LE_EMAIL"); else args+=(--register-unsafely-without-email); fi
for n in "${ready[@]}"; do args+=(-d "$n"); done
certbot "${args[@]}"
systemctl reload nginx

# ---- 5. the stack: only nginx may reach it, public URLs on the domains ----
cd "$DIR/deploy"
setenv() { if grep -q "^$1=" .env; then sed -i "s|^$1=.*|$1=$2|" .env; else echo "$1=$2" >> .env; fi; }
setenv SITE_BIND 127.0.0.1:8120
setenv ADMIN_BIND 127.0.0.1:8121
setenv REGISTER_BIND 127.0.0.1:8122
setenv PUBLIC_BASE_URL "https://$MAIN"
setenv REGISTER_PUBLIC_URL "https://ariza.$MAIN"

log "Rebuilding with the new addresses"
"$DIR/deploy/deploy.sh"

log "Done:"
echo "  Site:          https://$MAIN"
echo "  Admin:         https://admin.$MAIN"
echo "  Registration:  https://ariza.$MAIN"
for d in "${EXTRA[@]}"; do echo "  $d → https://$MAIN"; done
